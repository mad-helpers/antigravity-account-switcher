#!/usr/bin/env python3
"""Deterministic pure-stdlib bundler for src/injector/00..05_*.js -> antigravity_quota_injector.js."""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "src" / "injector"
DEFAULT_OUT = ROOT / "antigravity_quota_injector.js"
MODULE_RE = re.compile(r"^0[0-5]_[a-z0-9_]+\.js$")


def collect_sources(src_dir: Path = SRC_DIR) -> list[Path]:
    files = sorted(
        (p for p in src_dir.iterdir() if p.is_file() and MODULE_RE.match(p.name)),
        key=lambda p: p.name,
    )
    if len(files) != 6:
        raise RuntimeError(f"Expected 6 numbered modules (00..05) in {src_dir}, found {[p.name for p in files]}")
    return files


def build_bundle_text(src_dir: Path = SRC_DIR) -> str:
    sources = collect_sources(src_dir)
    parts: list[str] = []
    hasher = hashlib.sha256()
    for path in sources:
        text = path.read_bytes().decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
        if not text.endswith("\n"):
            text += "\n"
        hasher.update(path.name.encode("utf-8"))
        hasher.update(b"\n")
        hasher.update(text.encode("utf-8"))
        parts.append(f"// === {path.name} ===\n{text}")
    digest = hasher.hexdigest()[:16]
    body = "\n".join(parts).rstrip("\n")
    return f'(() => {{\n"use strict";\n// Generated by scripts/build_bundle.py | sha256:{digest} — DO NOT EDIT DIRECTLY\n\n{body}\n}})();\n'


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compile src/injector/00..05_*.js into antigravity_quota_injector.js")
    parser.add_argument("--check", action="store_true", help="Verify antigravity_quota_injector.js matches src/injector/* byte-for-byte")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Output bundle path")
    args = parser.parse_args(argv)

    expected = build_bundle_text(SRC_DIR)
    expected_bytes = expected.encode("utf-8")

    if args.check:
        if not args.out.is_file():
            print(f"FAIL: missing bundle {args.out}", file=sys.stderr)
            return 1
        actual_bytes = args.out.read_bytes()
        normalized_actual = actual_bytes.replace(b"\r\n", b"\n")
        if normalized_actual != expected_bytes:
            print(
                f"FAIL: {args.out.name} is out of sync with src/injector/* "
                f"(actual {len(normalized_actual)} bytes != expected {len(expected_bytes)} bytes). "
                "Run: python3 scripts/build_bundle.py",
                file=sys.stderr,
            )
            return 1
        eol_note = "exact LF" if actual_bytes == expected_bytes else "CRLF-normalized"
        print(f"OK: {args.out.name} matches src/injector/* byte-for-byte ({len(expected_bytes)} bytes, {eol_note})")
        return 0

    args.out.write_bytes(expected_bytes)
    print(f"Built {args.out.name} ({len(expected_bytes)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
